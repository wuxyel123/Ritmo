// WMA road age standards (2025 edition), extracted from the maintained
// Age-Grade-Tables dataset (AlanLyttonJones — the tables parkrun-style age
// grading is built on). `standards[age]` is the best expected time in
// SECONDS for that age and sex; age-grade % = standard / actualTime × 100.
// Only the four canonical road distances are shipped — grading any other
// distance would require interpolation the source doesn't define.
// Generated 2026-07-10 — regenerate from the source tables, don't hand-edit.

public enum AgeGrading {

    public enum Distance: CaseIterable {
        case fiveK, tenK, halfMarathon, marathon

        public var meters: Double {
            switch self {
            case .fiveK:        return 5_000
            case .tenK:         return 10_000
            case .halfMarathon: return 21_097.5
            case .marathon:     return 42_195
            }
        }

        /// Match a logged race distance to a canonical one (±1%).
        public static func match(meters: Double) -> Distance? {
            allCases.first { abs($0.meters - meters) / $0.meters <= 0.01 }
        }
    }

    /// Age-grade percentage (0–100+) or nil when inputs are out of range.
    public static func percent(distance: Distance, timeSeconds: Double,
                               age: Int, isFemale: Bool) -> Double? {
        guard timeSeconds > 0 else { return nil }
        let table = isFemale ? femaleStandards[distance]! : maleStandards[distance]!
        let clamped = min(max(age, table.baseAge), table.baseAge + table.seconds.count - 1)
        let standard = Double(table.seconds[clamped - table.baseAge])
        return standard / timeSeconds * 100
    }

